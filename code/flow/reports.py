"""Generate the M6 flow/restore diagnostics Markdown report from real runs."""
import argparse
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from evaluation.m6_metrics import evaluate
from flow.main import ROOT, run_all
from intent.classifier import DELETE

OUT = ROOT / 'code/evaluation/checkpoints/M6_FLOW_DIAGNOSTICS.md'


def table(header, rows):
    lines = ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    lines += ['| ' + ' | '.join(str(c) for c in row) + ' |' for row in rows]
    return '\n'.join(lines)


def counts(counter):
    return ', '.join(f'{k} {v}' for k, v in sorted(counter.items())) or 'none'


def m4_states(case):
    states = {}
    for d in case['policy']['decisions']:
        states.setdefault((d['system_id'], d['resource_id']), set()).add(d['observed_state'])
    return states


def report(full, sample, metrics):
    assessments = [(c, a) for c in full['cases'] for a in c['flows'] + c['restores']]
    deletion = [(c, a) for c, a in assessments if c['intent'] == DELETE]
    out = ['# M6 flow and restore diagnostics', '',
           'Generated by `python3 code/flow/reports.py` from the 518-case run, the 32-sample run and',
           '`code/evaluation/m6_metrics.py` (the only part that reads sample gold). Assessments are per',
           'case and per process resource; one resource can appear in several cases.', '',
           '## 1. Assessment counts (518 evaluation requests)', '']
    rows = []
    for kind in ('DATA_FLOW', 'RESTORE_PATH'):
        for scope, items in (('all requests', assessments), ('deletion-authorising', deletion)):
            c = Counter(a['status'] for _, a in items if a['kind'] == kind)
            rows.append((kind, scope, sum(c.values()), counts(c)))
    out += [table(('Kind', 'Requests', 'Assessments', 'Status'), rows), '']
    out += ['Source-backed attribution of every assessment: ' + counts(Counter(
                f'{a["kind"]}:{a["attribution"] or "no deciding reading"}' for _, a in assessments)) + '.',
            '', 'Deciding evidence class of supported assessments: ' + counts(Counter(
                f'{a["kind"]}:{a["deciding"]["evidence_class"]}' for _, a in assessments if a['supported'])) + '.',
            '', f'Ownership conflicts: {full["ownership_conflicts"]}; assessments with later unverified '
            f'workflow claims: {full["later_unverified_claims"]}; DELETE_RECORD obligations on backups: '
            f'{full["delete_steps_on_backups"]}; M4-linked process resources M6 did not attribute: '
            f'{full["m4_linked_not_attributed"]}.', '']
    retained = Counter((tuple(a['retention']['m5_required_actions']), a['retention']['delete_forbidden'])
                       for c in full['cases'] for a in c['restores'])
    out += ['Backup archive records under M5 (required action, delete forbidden): ' +
            ', '.join(f'{list(k[0])}/{k[1]} {v}' for k, v in sorted(retained.items())) + '.', '']
    out += ['## 2. Relation to M4 states', '',
            'M6 never changes an M4 state. M4 latest state(s) of each assessed process resource against its',
            'M6 status; UNKNOWN -> supported rows come from service telemetry or inventory listings that M4',
            'does not read as state:', '']
    moved = Counter()
    for c, a in assessments:
        states = m4_states(c).get((a['system_id'], a['resource_id']), set())
        moved[(','.join(sorted(states)) or 'not in M4', a['status'])] += 1
    out += [table(('M4 latest state(s)', 'M6 status', 'Assessments'),
                  [(k[0], k[1], v) for k, v in sorted(moved.items())]), '']
    out += ['## 3. Unsupported assessments', '',
            'UNKNOWN and CONFLICTING assessments carry no obligations and keep a case from being COMPLETE.', '']
    rows = [(c['case_id'], a['resource_id'], a['status'], a['reason']) for c, a in assessments if not a['supported']]
    out += [table(('Case', 'Resource', 'Status', 'Reason'), rows) if rows else 'None.', '']
    out += ['## 4. Dependencies for M7', '', 'Edge kinds over all requests: ' + counts(Counter(
        e['kind'] for c in full['cases'] for e in c['dependencies'])) + '.', '',
            'Precedence recommendations: ' + counts(Counter(
                r['strength'] for c in full['cases'] for r in c['precedence'])) + '.', '']
    out += ['## 5. Sample assessments', '']
    rows = [(c['case_id'], a['resource_id'], a['status'], a['attribution'] or '',
             (a['deciding'] or {}).get('evidence_id', ''), (a['deciding'] or {}).get('evidence_class', ''))
            for c in sample['cases'] for a in c['flows'] + c['restores']]
    out += [table(('Case', 'Resource', 'Status', 'Attribution', 'Deciding evidence', 'Class'), rows), '']
    out += ['## 6. Development and holdout scores (evaluation only)', '']
    rows = []
    for split in ('dev', 'holdout'):
        p = metrics['process_steps'][split]
        rows.append((split, p['expected'], p['predicted'], p['matched'], f'{p["precision"]:.4f}',
                     f'{p["recall"]:.4f}', p['evidence_id_match'], len(p['missed']), len(p['extra'])))
    out += [table(('Split', 'Expected', 'Predicted', 'Matched', 'Precision', 'Recall', 'evidence_id', 'Missed',
                   'Extra'), rows), '']
    for split in ('dev', 'holdout'):
        for item in metrics['process_steps'][split]['missed']:
            out.append(f'- {split} missed {item["case_id"]} {item["step"]}: {item["root_cause"]}')
        for item in metrics['process_steps'][split]['extra']:
            out.append(f'- {split} extra {item["case_id"]} {item["step"]}: {item["basis"]}')
    rows = []
    for split in ('dev', 'holdout'):
        for label in ('before_m6', 'after_m6'):
            m = metrics['provisional_steps'][split][label]
            rows.append((split, label, m['status_correct'], m['step_precision'], m['step_recall'], m['step_f1'],
                         m['field_accuracy'], m['sequence_accuracy']))
    out += ['', 'Provisional combined steps (M5 + M6, operation-table order, no M7 citation guard):', '',
            table(('Split', 'Run', 'Status', 'Step P', 'Step R', 'Step F1', 'Field acc', 'Sequence acc'), rows), '']
    return '\n'.join(out)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dataset', type=Path, default=ROOT / 'dataset')
    parser.add_argument('--cache', type=Path, default=Path('/tmp/m4-ingest-cache'))
    args = parser.parse_args()
    full = run_all(args.dataset, False, args.cache)
    sample = run_all(args.dataset, True, args.cache)
    OUT.write_text(report(full, sample, evaluate(args.dataset, args.cache)), encoding='utf-8')
    print(OUT)
