"""Generate the M7 report on INCOMPLETE rows that have no evidenced finding.

    python3 code/synthesis/reports.py   # writes code/evaluation/checkpoints/M7_INCOMPLETE_WITHOUT_FINDINGS.md

Production data only (518 requests); no sample answers are read.
"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from evaluation.contract import load_context, validate_rows
from synthesis.main import run

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / 'code/evaluation/checkpoints/M7_INCOMPLETE_WITHOUT_FINDINGS.md'
CLASSES = (('treatment decided', 'unknown state'), ('M4 state is unresolved', 'unknown state'),
           ('identifiers were removed', 'unknown state'),
           ('condition is UNKNOWN', 'unknown conditional treatment'),
           ('condition FALSE and no supplied rule', 'unknown conditional treatment'),
           ('no policy category', 'missing policy mapping'), ('conflicting category', 'missing policy mapping'),
           ('another person', 'contested attribution'), ('contested attribution', 'contested attribution'),
           ('citation rejected', 'citation rejection'), ('M6 ', 'process state unknown'),
           ('not available', 'retained record not observed'), ('must be retained is absent', 'retained record not observed'))


def reason_class(reason):
    return next((label for needle, label in CLASSES if needle in reason), 'other: ' + reason)


def analyse(rows, diagnostics):
    out = []
    for row in rows:
        if row['deletion_status'] != 'INCOMPLETE': continue
        if any(s['phase'] == 'FINDING' for s in row['steps_json']): continue
        d = diagnostics[row['case_id']]
        classes = Counter(reason_class(u['reason']) for u in d.get('unresolved', ()))
        linked = len(d.get('items', ()))
        category = ('no linked resources' if not linked else
                    'future-only checks' if row['steps_json'] else 'undecided treatments only')
        out.append({'case_id': row['case_id'], 'category': category, 'linked': linked,
                    'steps': len(row['steps_json']), 'future_only': len(d.get('future_only', ())),
                    'classes': classes, 'rejected': len(d.get('citations_rejected', ())),
                    'unapplied_risk': sum(n['to'] is None for n in d.get('risk_overlay', ())),
                    'identity': d.get('resolution')})
    return out


def render(rows, diagnostics):
    requests, evidence = load_context(ROOT / 'dataset', 'full')
    strict = validate_rows(rows, requests, evidence)
    diagnostic = validate_rows(rows, requests, evidence, nonstandard_allow_unproven_incomplete=True)
    cases = analyse(rows, diagnostics)
    total = Counter()
    for c in cases: total.update(c['classes'])
    lines = ['# M7 – INCOMPLETE rows without an evidenced finding (generated)', '',
             'Generated by `python3 code/synthesis/reports.py` from the 518 evaluation requests. No sample answers '
             'are read. A row is listed when M7 marks it INCOMPLETE but has no FINDING step.', '',
             '## Validator results', '',
             '| Mode | Status | Errors | Rows with errors |', '|---|---|---|---|',
             f'| strict M0 (official contract check; the only mode valid for submission claims) | '
             f'{"PASS" if strict.valid else "FAIL"} | {len(strict.errors)} | '
             f'{len({e.split(":")[0] for e in strict.errors})} |',
             f'| diagnostic, NONSTANDARD (`nonstandard_allow_unproven_incomplete=True`) | '
             f'{"PASS" if diagnostic.valid else "FAIL"} | {len(diagnostic.errors)} | '
             f'{len({e.split(":")[0] for e in diagnostic.errors})} |', '',
             '## Summary', '',
             f'- Rows: **{len(cases)}**. By shape: ' + ', '.join(f'{k} {v}' for k, v in sorted(
                 Counter(c["category"] for c in cases).items())) + '.',
             f'- Future-only checks in these rows: {sum(c["future_only"] for c in cases)}. '
             f'Citation rejections: {sum(c["rejected"] for c in cases)}. '
             f'Unapplied risk readings: {sum(c["unapplied_risk"] for c in cases)}.',
             '- Unresolved items by cause: ' + ', '.join(f'{k} {v}' for k, v in sorted(total.items())) + '.', '',
             '## Is a strict, source-grounded plan possible?', '',
             'No, for every row below. The strict plan shape needs a FINDING, and a FINDING needs a citation '
             'that proves the record present or exposed (or the process active) at `audit_at`. In each row, no '
             'admissible, subject-owned observation proves that. The causes are an UNKNOWN M4 state with no '
             'risk-direction reading of the same physical copy, an undecided policy condition (for example a '
             'security audit record without a supplied retention period), a missing category mapping, a '
             'contested attribution, or no linked resource at all. The only alternatives are to invent a '
             'finding, or to call the case COMPLETE while things are unknown. Both are forbidden. This is an '
             'unresolved conflict between the strict plan shape and the evidence, and it is left visible.', '',
             '| case | shape | linked items | steps | future-only | unresolved causes |', '|---|---|---|---|---|---|']
    for c in cases:
        causes = '; '.join(f'{k} {v}' for k, v in sorted(c['classes'].items())) or '—'
        lines.append(f'| {c["case_id"]} | {c["category"]} | {c["linked"]} | {c["steps"]} | {c["future_only"]} | '
                     f'{causes} |')
    return '\n'.join(lines) + '\n', cases, strict, diagnostic


def main():
    rows, diagnostics, _ = run(ROOT / 'dataset', False, Path('/tmp/m4-ingest-cache'))
    text, _, _, _ = render(rows, diagnostics)
    TARGET.write_text(text, encoding='utf-8')
    print(TARGET)


if __name__ == '__main__':
    main()
