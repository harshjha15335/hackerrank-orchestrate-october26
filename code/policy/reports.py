"""Generate the M5 UNKNOWN root-cause and condition-coverage Markdown reports from a run."""
import argparse
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from intent.classifier import DELETE
from policy.main import ROOT, run_all
from policy.unknowns import CAUSES

OUT = ROOT / 'code/evaluation/checkpoints'
CAUSE_TEXT = {
    'operational_claim_without_readback': 'Operational claims without readbacks (FOUND/NOT_FOUND lookups, handover statuses, scan or worker events)',
    'missing_field_level_state': 'Missing field-level state (record or completed readback seen, but no M4 rule turns its fields into a state)',
    'insufficient_identity_attribution': 'Insufficient identity attribution (mixed-identity context)',
    'timestamp_anomaly': 'Timestamp anomalies (record time after manifest capture or cutoff; quarantined)',
    'unsupported_source_scope': 'Unsupported source scope (system/resource columns not recognised, e.g. misaligned log columns)',
    'conflicting_facts': 'Conflicting equal-time facts',
    'other': 'Other documented causes',
}


def table(header, rows):
    lines = ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    lines += ['| ' + ' | '.join(str(c) for c in row) + ' |' for row in rows]
    return '\n'.join(lines)


def unknown_report(full, sample):
    rows = full['unknown_root_causes']
    intent = {c['case_id']: c['intent'] for c in full['cases']}
    primary = Counter(r['primary_cause'] for r in rows)
    any_cause = Counter(c for r in rows for c in r['causes'])
    relevant = [r for r in rows if r['policy_relevant']]
    deletion = [r for r in relevant if intent[r['case_id']] == DELETE]
    out = ['# M5 UNKNOWN root-cause report', '',
           'Generated by `python3 code/policy/reports.py` from the 518-case run. Each row is one M4 latest',
           'physical-copy assertion with no source-supported state. M5 does not change M4 states; it only',
           'classifies why each stays UNKNOWN and whether a policy obligation depends on it.', '',
           f'Unresolved latest assertions: **{len(rows)}** across {len({r["case_id"] for r in rows})} cases.', '',
           '## Primary cause', '',
           'A copy can have several contributing causes (one per assertion in its history); the primary cause',
           'is the first in the order below.', '',
           table(('Cause', 'Primary', 'Contributing'),
                 [(CAUSE_TEXT[c], primary.get(c, 0), any_cause.get(c, 0)) for c in CAUSES]), '',
           '## Policy relevance', '',
           f'- Mapped to a deletion_rules.csv category: **{sum(r["category_status"] == "MAPPED" for r in rows)}**',
           f'- Process resources whose flow obligation belongs to M6: **{sum(r["category_status"] == "PROCESS" for r in rows)}**',
           f'- No policy category (unmapped or ambiguous): **{sum(r["category_status"] not in ("MAPPED", "PROCESS") for r in rows)}**',
           f'- Relevant to a policy or flow obligation: **{len(relevant)}**, of which **{len(deletion)}** are in',
           '  requests that authorise deletion (the rest belong to NOT_APPLICABLE requests).', '',
           '## Cause by policy category', '',
           table(('Primary cause', 'Category', 'Copies'),
                 sorted(((CAUSE_TEXT[c].split(' (')[0], cat or '(none)', n) for (c, cat), n in
                         Counter((r['primary_cause'], r['category']) for r in rows).items()),
                        key=lambda t: (-t[2], t[0], t[1]))), '',
           '## Cause by source', '',
           table(('Primary cause', 'Evidence file(s)', 'Copies'),
                 [(CAUSE_TEXT[c].split(' (')[0], ', '.join(ev), n) for (c, ev), n in
                  Counter((r['primary_cause'], tuple(r['evidence'])) for r in rows).most_common(15)]), '',
           'Only the 15 largest source groups are listed; the per-copy rows are in the CLI output',
           '(`python3 code/policy/main.py` → `unknown_root_causes`).', '',
           '## Sample split', '',
           f'The 32 public samples have {len(sample["unknown_root_causes"])} unresolved latest assertions; primary causes: ' +
           ', '.join(f'{k} {v}' for k, v in sorted(Counter(r['primary_cause'] for r in sample['unknown_root_causes']).items())) + '.',
           '']
    return '\n'.join(out)


def coverage_report(full, sample, tests):
    out = ['# M5 policy condition-coverage report', '',
           'Generated by `python3 code/policy/reports.py`. Counts are physical-copy decisions (one per M4',
           'latest assertion). Fixture coverage lists the outcomes exercised by `code/policy/tests`.', '']
    rows = []
    for rule in full['rules']:
        for label, run in (('518 eval', full), ('32 sample', sample)):
            counts = Counter(d['condition_outcome'] for c in run['cases'] for d in c['decisions']
                             if d['rule_id'] == rule['rule_id'])
            compliance = Counter(d['compliance'] for c in run['cases'] for d in c['decisions']
                                 if d['rule_id'] == rule['rule_id'])
            rows.append((rule['rule_id'] if label == '518 eval' else '', rule['data_category'] if label == '518 eval' else '',
                         rule['required_action'] if label == '518 eval' else '', label,
                         counts.get('TRUE', 0), counts.get('FALSE', 0), counts.get('UNKNOWN', 0),
                         compliance.get('COMPLIANT', 0), compliance.get('VIOLATION', 0), compliance.get('UNRESOLVED', 0),
                         ', '.join(sorted(tests.get(rule['data_category'], ()))) if label == '518 eval' else ''))
    out.append(table(('Rule', 'Category', 'Action', 'Run', 'TRUE', 'FALSE', 'UNKNOWN', 'Compliant', 'Violation',
                      'Unresolved', 'Fixture outcomes'), rows))
    status = Counter(d['category_status'] for c in full['cases'] for d in c['decisions'])
    out += ['', f'Category mapping over 518 cases: ' + ', '.join(f'{k} {v}' for k, v in sorted(status.items())) + '.',
            f'DELETE steps proposed for RETAIN categories: **{full["retain_category_delete_steps"]}**.', '']
    return '\n'.join(out)


def fixture_outcomes():
    """Outcomes declared by the test module's coverage table (single source of truth)."""
    from policy.tests.test_policy import COVERAGE
    found = defaultdict(set)
    for category, outcome in COVERAGE:
        found[category].add(outcome)
    return found


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dataset', type=Path, default=ROOT / 'dataset')
    parser.add_argument('--cache', type=Path, default=Path('/tmp/m4-ingest-cache'))
    args = parser.parse_args()
    full = run_all(args.dataset, False, args.cache)
    sample = run_all(args.dataset, True, args.cache)
    (OUT / 'M5_UNKNOWN_ROOT_CAUSES.md').write_text(unknown_report(full, sample), encoding='utf-8')
    (OUT / 'M5_CONDITION_COVERAGE.md').write_text(coverage_report(full, sample, fixture_outcomes()), encoding='utf-8')
    print('wrote', OUT / 'M5_UNKNOWN_ROOT_CAUSES.md', OUT / 'M5_CONDITION_COVERAGE.md')
